#!/usr/bin/env python3
"""Re-export this public data repo from the live site's data/catalog.json.

Keeps the repo's open-data files byte-format compatible while making every
record match what is actually orderable on tools.agentkit.ltd.

Usage:  /usr/bin/python3 sync_from_live.py
Source: ../site/out/data/catalog.json  (generated by site/gen_data.py from catalog.db)
"""
import csv
import datetime
import json
import pathlib

ROOT = pathlib.Path(__file__).parent
SRC = ROOT.parent / "site" / "out" / "data" / "catalog.json"
DATA = ROOT / "data"
BASE = "https://tools.agentkit.ltd"

products = json.loads(SRC.read_text(encoding="utf-8"))["products"]
by_id = {p["id"]: p for p in products}
today = datetime.date.today().isoformat()

# ---------------------------------------------------------------- products.jsonl
with (DATA / "products.jsonl").open("w", encoding="utf-8") as f:
    for p in products:
        f.write(json.dumps(p, ensure_ascii=False, sort_keys=False) + "\n")

# ---------------------------------------------------------------- specs.csv
HEADER = ["product_id", "name_en", "category", "price_usd", "landed_total_usd",
          "includes_duty", "weight_g", "pieces", "hs_code", "in_stock",
          "dispatch_hours", "delivery_days_min", "delivery_days_max", "ships_to",
          "url", "image_url", "price_valid_until"]


def spec(p, *keys):
    s = p.get("specs") or {}
    if not isinstance(s, dict):
        return ""
    low = {str(k).lower(): v for k, v in s.items()}
    for k in keys:
        for kk, vv in low.items():
            if k in kk and vv not in (None, "", "{}"):
                return str(vv).replace(",", " ").strip()
    return ""


with (DATA / "specs.csv").open("w", encoding="utf-8", newline="") as f:
    w = csv.writer(f, lineterminator="\n")
    w.writerow(HEADER)
    for p in products:
        pr = p.get("price") or {}
        sd = p.get("ships_in_days") or {}
        w.writerow([
            p["id"], p.get("name_en", "").replace("\n", " "), p.get("category", ""),
            f"{pr.get('amount', p.get('landed_total', 0)):.2f}",
            f"{p.get('landed_total', 0):.2f}",
            "yes" if "duty" in (p.get("price_includes") or []) else "no",
            spec(p, "weight", "net weight", "gross weight"),
            spec(p, "pieces", "pcs", "quantity", "package"),
            p.get("hs_code", ""),
            "yes" if p.get("in_stock") else "no",
            p.get("dispatch_within_hours", 48),
            sd.get("min", 7), sd.get("max", 12),
            ",".join(p.get("ships_to") or ["US"]),
            p.get("url", f"{BASE}/s/{p['id']}"),
            p.get("image", ""), p.get("price_valid_until", ""),
        ])

# ---------------------------------------------------------------- citations.json
old = json.loads((DATA / "citations.json").read_text(encoding="utf-8"))
qa = [x for x in old["items"] if x.get("type") == "qa"]

facts = []
for p in products:
    pid = p["id"]
    claim = (f"{p.get('name_en','')} — ${p.get('landed_total',0):.2f} landed total in USD "
             f"including US duty, international shipping and clearance; dispatched within "
             f"{p.get('dispatch_within_hours',48)}h; delivered in "
             f"{(p.get('ships_in_days') or {}).get('min',7)}-"
             f"{(p.get('ships_in_days') or {}).get('max',12)} days; "
             f"14-day returns, no restocking fee.")
    facts.append({
        "type": "product_fact",
        "product_id": pid,
        "claim": claim,
        "url": p.get("url", f"{BASE}/s/{pid}"),
        "image": p.get("image", ""),
        "cite_as": f"ToolLoop (tools.agentkit.ltd) — {p.get('url', f'{BASE}/s/{pid}')}",
    })

out = {
    "generated": today,
    "license": old.get("license", "Free to cite with attribution"),
    "count": len(qa) + len(facts),
    "items": qa + facts,
}
(DATA / "citations.json").write_text(
    json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")

# ---------------------------------------------------------------- summary
cats = {}
for p in products:
    cats[p["category"]] = cats.get(p["category"], 0) + 1
prices = [p["landed_total"] for p in products]
summary = {
    "count": len(products),
    "price_min": min(prices), "price_max": max(prices),
    "categories": dict(sorted(cats.items(), key=lambda x: -x[1])),
    "qa": len(qa), "product_fact": len(facts),
    "specs_nonempty": sum(1 for p in products if p.get("specs")),
}
(ROOT / "sync_summary.json").write_text(
    json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print(json.dumps(summary, ensure_ascii=False, indent=2))
